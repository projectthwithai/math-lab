export function buildStandardSubtopicPatterns(): SolutionPattern[] {
  const patterns: SolutionPattern[] = [];

  for (const subtopic of SUBTOPICS) {
    const unit = getUnitById(subtopic.unitId);
    const subject: Subject = unit?.subject ?? 'math';
    const unitTitle = unit?.title ?? subtopic.title;
    const questions = EXAMPLES[subtopic.id] ?? defaultExamples(subtopic.title);
    const strategies = defaultStrategies(subtopic.title);
    const slug = subtopic.id.replace(/^st-/, '');

    PATTERN_STAR_ARCHETYPES.forEach((archetype, index) => {
      patterns.push({
        id: `sp-${slug}-t${archetype.star}`,
        subject,
        unit: unitTitle,
        unitId: subtopic.unitId,
        subtopicId: subtopic.id,
        level: archetype.level,
        difficulty: archetype.star,
        patternName: `${archetype.typeLabel}: ${subtopic.title}`,
        exampleQuestion: questions[index],
        strategyText: strategies[index],
      });
    });
  }

  return patterns;
}
